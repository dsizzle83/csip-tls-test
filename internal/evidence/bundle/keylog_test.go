// --- end-to-end through Builder.Write ---------------------------------------

// TestBundleWriteFiltersKeyLogToCapture exercises the actual call site
// (write.go) rather than writeFilteredKeyLog directly: a bundle built from a
// capture holding one session and a key log naming two must ship only the
// one the capture actually contains, and must record the kept/dropped
// counts on the Builder.
func TestBundleWriteFiltersKeyLogToCapture(t *testing.T) {
	work := t.TempDir()
	inScope, outOfScope := randomOf(0xAA), randomOf(0xBB)

	capturePath := filepath.Join(work, "run.pcapng")
	writeKeylogCapture(t, capturePath, [][32]byte{inScope})

	keylogPath := filepath.Join(work, "bench-shared.keylog")
	lines := []string{
		"CLIENT_RANDOM " + hex.EncodeToString(inScope[:]) + " " + strings.Repeat("aa", 48),
		"CLIENT_RANDOM " + hex.EncodeToString(outOfScope[:]) + " " + strings.Repeat("bb", 48),
	}
	if err := os.WriteFile(keylogPath, []byte(strings.Join(lines, "\n")+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	b := NewBuilder(RunMeta{Tool: "evidence-engine-test", Operator: "bench"})
	b.SetCapture(capture.Summary{Tool: "dumpcap", Format: "pcapng"}, capturePath)
	b.SetKeyLog(keylogPath)
	b.AddCase(TestCaseResult{ID: "KL-1", Title: "keylog scoping fixture", Verdict: Pass})

	dir := filepath.Join(work, "bundle")
	bd, err := b.Write(dir)
	if err != nil {
		t.Fatalf("Write: %v", err)
	}

	if got := b.KeyLogLinesKept(); got != 1 {
		t.Errorf("KeyLogLinesKept() = %d, want 1", got)
	}
	if got := b.KeyLogLinesDropped(); got != 1 {
		t.Errorf("KeyLogLinesDropped() = %d, want 1", got)
	}

	// REV0907-E5's TODO: the same counts must be readable off the WRITTEN
	// bundle itself, not only off the live Builder — so a reader of
	// bundle.json back later (or Load(dir).Run.KeyLog) sees the filtering
	// result without re-deriving it.
	if bd.Run.KeyLog == nil {
		t.Fatal("bundle.json's run.keylog is nil; the filter counts did not reach RunMeta")
	}
	if bd.Run.KeyLog.LinesKept != 1 || bd.Run.KeyLog.LinesDropped != 1 {
		t.Errorf("run.keylog = %+v, want {LinesKept:1 LinesDropped:1}", *bd.Run.KeyLog)
	}
	loaded, err := Load(dir)
	if err != nil {
		t.Fatalf("Load: %v", err)
	}
	if loaded.Run.KeyLog == nil || loaded.Run.KeyLog.LinesKept != 1 || loaded.Run.KeyLog.LinesDropped != 1 {
		t.Errorf("bundle.json round-trips run.keylog as %+v, want {LinesKept:1 LinesDropped:1}", loaded.Run.KeyLog)
	}

	if bd.Files.KeyLog == "" {
		t.Fatal("bundle.json records no key log file")
	}
	raw, err := os.ReadFile(filepath.Join(dir, bd.Files.KeyLog))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(raw), hex.EncodeToString(outOfScope[:])) {
		t.Fatal("bundle shipped a key-log line for a session outside its own capture")
	}
	if !strings.Contains(string(raw), hex.EncodeToString(inScope[:])) {
		t.Fatal("bundle dropped a key-log line for a session that IS in its own capture")
	}

	mustVerify(t, dir)
}

